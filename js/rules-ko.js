    let out = '';
    for (let i = 0; i < 19 * 21; i++) {
      const ch = String.fromCharCode(0xac00 + i * 28 + finalIndex);
      if (!exclude || exclude.indexOf(ch) === -1) out += ch;
    }
    return '[' + out + ']';
